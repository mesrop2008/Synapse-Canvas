"""Where uploaded files are kept. Callers see keys, never paths, so an object
store can replace the local filesystem without touching them.

Keys are generated by the app (`{workspace_id}/{source_id}`); anything else
is refused, so no filename a user chose can reach the filesystem."""

from __future__ import annotations

import asyncio
import os
import re
import shutil
import tempfile
from abc import ABC, abstractmethod
from pathlib import Path
from typing import BinaryIO

from api.core.config import Settings

_KEY = re.compile(r"^[A-Za-z0-9_-]+(?:/[A-Za-z0-9_-]+)*$")


def _check(key: str) -> str:
    if not _KEY.match(key):
        raise ValueError(f"Not a storage key: {key!r}")
    return key


class SourceStorage(ABC):
    @abstractmethod
    async def save(self, key: str, data: BinaryIO) -> None:
        """Copies `data` from its current position to the end."""

    @abstractmethod
    async def read(self, key: str) -> bytes: ...

    @abstractmethod
    async def delete(self, key: str) -> None:
        """A missing key is not an error."""

    @abstractmethod
    async def delete_prefix(self, prefix: str) -> None:
        """Everything under `prefix/`; a missing prefix is not an error."""


class LocalFileStorage(SourceStorage):
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        return self.root.joinpath(*_check(key).split("/"))

    async def save(self, key: str, data: BinaryIO) -> None:
        path = self._path(key)

        def write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            # Renamed into place, so a crash never leaves half a file behind
            # the key.
            handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
            try:
                with os.fdopen(handle, "wb") as out:
                    shutil.copyfileobj(data, out)
                os.replace(temporary, path)
            except BaseException:
                Path(temporary).unlink(missing_ok=True)
                raise

        await asyncio.to_thread(write)

    async def read(self, key: str) -> bytes:
        return await asyncio.to_thread(self._path(key).read_bytes)

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(self._path(key).unlink, missing_ok=True)

    async def delete_prefix(self, prefix: str) -> None:
        await asyncio.to_thread(shutil.rmtree, self._path(prefix), ignore_errors=True)


def build_storage(settings: Settings) -> SourceStorage:
    return LocalFileStorage(Path(settings.source_storage_dir))
